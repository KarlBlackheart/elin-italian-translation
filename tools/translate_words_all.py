def run():
    wb = openpyxl.load_workbook('Lang/IT/Game/Word.xlsx')
    ws = wb.active
    headers = {ws.cell(row=1, column=c).value: c for c in range(1, ws.max_column+1)}

    W = get_word_map()
    count = 0

    for r in range(2, ws.max_row+1):
        wid = str(ws.cell(row=r, column=headers['id']).value)
        if wid in W:
            ws.cell(row=r, column=headers['name']).value = W[wid]
            count += 1

    wb.save('Lang/IT/Game/Word.xlsx')
    print(f'Applied {count} translations to Word.xlsx')

if __name__ == '__main__':
    run()
