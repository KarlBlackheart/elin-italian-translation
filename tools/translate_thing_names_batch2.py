def run():
    wb = openpyxl.load_workbook(THING_FILE)
    ws = wb['Thing']
    headers = {ws.cell(1, c).value: c for c in range(1, ws.max_column+1)}

    name_c = headers['name']
    en_c = headers['name_EN']
    
    count = 0
    for r in range(2, ws.max_row+1):
        en = ws.cell(r, en_c).value
        if en and str(en).strip() in NAMES_BATCH_2:
            ws.cell(r, name_c, NAMES_BATCH_2[str(en).strip()])
            count += 1

    wb.save(THING_FILE)
    print(f"Batch 2 applied {count} name translations to Thing.xlsx")

if __name__ == '__main__':
    run()
