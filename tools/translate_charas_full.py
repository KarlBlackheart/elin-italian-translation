def run():
    wb = openpyxl.load_workbook(CHARA_FILE)
    ws = wb.active
    headers = {ws.cell(1, c).value: c for c in range(1, ws.max_column + 1) if ws.cell(1, c).value}
    name_c = headers['name']
    aka_c = headers['aka']
    
    updated_name = 0
    updated_aka = 0
    for row, (name_it, aka_it) in CHARA_UPDATES.items():
        if name_it is not None:
            ws.cell(row=row, column=name_c, value=name_it)
            updated_name += 1
        if aka_it is not None:
            ws.cell(row=row, column=aka_c, value=aka_it)
            updated_aka += 1
            
    wb.save(CHARA_FILE)
    print(f"Updated {updated_name} names and {updated_aka} akas in Chara.xlsx!")

if __name__ == "__main__":
    run()
