file_p = 'd:/Mod/Elin/Lang/IT/Game/Chara.xlsx'
wb = openpyxl.load_workbook(file_p)
ws = wb.active
headers = [str(c.value) for c in ws[1]]
name_col = headers.index('name') + 1
name_en_col = headers.index('name_EN') + 1

count = 0
for r in range(2, ws.max_row + 1):
    n_en = str(ws.cell(row=r, column=name_en_col).value or '').strip()
    if n_en in chara_names_it:
        ws.cell(row=r, column=name_col, value=chara_names_it[n_en])
        count += 1

wb.save(file_p)
print(f'Chara.xlsx translated {count} creature and NPC names!')
