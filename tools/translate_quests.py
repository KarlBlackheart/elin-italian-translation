file_p = 'd:/Mod/Elin/Lang/IT/Game/Quest.xlsx'
wb = openpyxl.load_workbook(file_p)
ws = wb.active
headers = [str(c.value) for c in ws[1]]
name_col = headers.index('name') + 1
detail_col = headers.index('detail') + 1

count = 0
for r in range(2, ws.max_row + 1):
    qid = str(ws.cell(row=r, column=1).value or '').strip()
    if qid in quests_data:
        name_it, detail_it = quests_data[qid]
        if name_it is not None:
            ws.cell(row=r, column=name_col, value=name_it)
        if detail_it is not None:
            ws.cell(row=r, column=detail_col, value=detail_it)
        count += 1

wb.save(file_p)
print(f'Quest.xlsx translated {count} quests and bulletin requests!')
