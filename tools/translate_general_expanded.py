ws = wb.active
headers = [str(c.value) for c in ws[1]]
id_col = headers.index('id') + 1
text_col = headers.index('text') + 1

count = 0
for r in range(2, ws.max_row + 1):
    rid = str(ws.cell(row=r, column=id_col).value or '').strip()
    if rid in general_translations:
        ws.cell(row=r, column=text_col, value=general_translations[rid])
        count += 1

wb.save(file_p)
print(f'General.xlsx translated/updated {count} key UI strings!')
