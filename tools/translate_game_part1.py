def apply():
    print(f"Loading {GAME_FILE}...")
    wb = openpyxl.load_workbook(GAME_FILE)
    ws = wb['Game']
    
    headers = {ws.cell(1, c).value: c for c in range(1, ws.max_column + 1)}
    col_id = headers['id']
    col_text = headers['text']
    
    updated = 0
    for r in range(2, ws.max_row + 1):
        row_id = ws.cell(r, col_id).value
        if row_id in TRANSLATIONS:
            ws.cell(r, col_text, TRANSLATIONS[row_id])
            updated += 1
            
    wb.save(GAME_FILE)
    print(f"Aggiornate con successo {updated} righe in Game.xlsx (Batch 1)")

if __name__ == '__main__':
    apply()
